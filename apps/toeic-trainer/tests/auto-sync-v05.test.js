assert.throws(()=>Auto.enable(store,{location:local}),/同網域|localhost/);
const t=new Date('2026-10-12T01:00:00Z');
const enabled=Auto.enable(store,{location:hosted,now:t});
assert.deepEqual(enabled,{version:1,enabled:true,enabledAt:t.toISOString()});
