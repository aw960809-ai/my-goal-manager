'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const Auto=require('../js/auto-sync.js'),Core=require('../js/core.js');
const root=path.resolve(__dirname,'..');
const map=new Map();
const store={getItem:k=>map.has(k)?map.get(k):null,setItem(k,v){map.set(k,v)}};
const hosted={protocol:'https:',pathname:'/my-goal-manager/apps/toeic-trainer/index.html',href:'https://aw960809-ai.github.io/my-goal-manager/apps/toeic-trainer/index.html'};
const local={protocol:'http:',pathname:'/',href:'http://127.0.0.1:8766/'};
assert.equal(Auto.hosted(hosted),true);
