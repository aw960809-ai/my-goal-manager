const disabled=Auto.disable(store);assert.equal(disabled.enabled,false);
assert.equal(disabled.enabledAt,t.toISOString());
const reenable=Auto.enable(store,{location:hosted,now:new Date('2026-10-12T03:00:00Z')});
assert.equal(reenable.enabledAt,'2026-10-12T03:00:00.000Z','Reenable does not silently import earlier sessions');
let messages=[];
const fakeWindow={location:hosted,localStorage:store,BroadcastChannel:class {constructor(name){assert.equal(name,'toeic-trainer-v05')}postMessage(v){messages.push(v)}close(){}}};
assert.equal(Auto.notifyCompleted({createdAt:'2026-10-12T02:59:59Z'},{window:fakeWindow}),false);
assert.equal(Auto.notifyCompleted({createdAt:'2026-10-12T03:01:00Z'},{window:fakeWindow}),true);
assert.deepEqual(messages,[{type:'new-submitted-session'}]);
assert.equal(Auto.notifyCompleted({createdAt:'2026-10-12T03:01:00Z'},{window:{...fakeWindow,location:local}}),false);
assert.equal(Core.KEY,'toeic-trainer-v01:learning-state');assert.equal(Core.SCHEMA,1);
